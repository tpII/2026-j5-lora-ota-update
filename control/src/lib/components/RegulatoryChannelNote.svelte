<div class="panel-note">
  <p>
    La banda de 915 a 928 MHz admite LoRa sin autorización individual solo como modulación de banda
    ancha, así que con antena se usan solo canales de 500 kHz, centrados entre 915,25 y 927,75 MHz y con
    unos 26 dBm como máximo en el conector de antena. Los canales de 125 y 250 kHz quedan para el banco,
    con cable coaxial y atenuadores o cargas de 50 Ω. El firmware no impone estos límites: la
    responsabilidad es del operador (ADR 0004).
  </p>
  <p class="mt-1">
    Nunca transmitir sin la antena conectada. Sobre la mesa, usar la potencia mínima y el LNA de la V4.3
    puenteado.
  </p>
</div>
